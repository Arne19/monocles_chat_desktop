//! Receiving live locations shared from monocles Android (`urn:xmpp:live-location:0`).
//!
//! A share starts with a normal location message: a `geo:lat,lon` body plus
//! `<live-location id expires/>`. The sender then sends body-less `no-store` messages with
//! `<live-location-update id lat lon/>` and finally `<live-location-stop id/>`. Like Android
//! (`MessageParser`), updates and stops are only believed inside a PQ OMEMO2 envelope; anyone
//! could add them to a plaintext stanza. In an OMEMO2 chat the namespace is also stripped from
//! the outer stanza (`messaging::is_unauthenticated_metadata`). An update can only move a share
//! of the same sender (crypto sender's bare JID) in the same conversation.

use minidom::Element;

pub const NS_LIVE_LOCATION: &str = "urn:xmpp:live-location:0";

/// Longest share we accept, counted from the starting message (Android offers up to 8 h).
const MAX_DURATION_SECS: i64 = 24 * 60 * 60;

/// A share starting with this message.
#[derive(Debug, Clone, PartialEq)]
pub struct LiveStart {
    pub session_id: String,
    /// Unix seconds, clamped to [`MAX_DURATION_SECS`] after the message.
    pub expires: i64,
}

/// What a body-less live-location message does.
#[derive(Debug, Clone, PartialEq)]
pub enum LiveControl {
    Update { session_id: String, lat: f64, lon: f64 },
    Stop { session_id: String },
}

/// Session ids are generated by the sender; we only take short, plain ones.
fn valid_session_id(id: &str) -> bool {
    (1..=64).contains(&id.len()) && id.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_')
}

fn session_id(el: &Element) -> Option<String> {
    el.attr("id").filter(|id| valid_session_id(id)).map(str::to_string)
}

/// The share a location message (`body` is a single `geo:` URI) starts, if it carries one.
/// `sent_at` is the message's unix time.
pub fn parse_start(content: &Element, body: &str, sent_at: i64) -> Option<LiveStart> {
    crate::map_tiles::parse_geo(body)?;
    let el = content.get_child("live-location", NS_LIVE_LOCATION)?;
    let session_id = session_id(el)?;
    let expires = chrono::DateTime::parse_from_rfc3339(el.attr("expires")?).ok()?.timestamp();
    Some(LiveStart { session_id, expires: expires.min(sent_at + MAX_DURATION_SECS) })
}

/// The share a received message starts, given its `encryption`. Only a PQ OMEMO2 message can
/// start one: updates are only believed inside OMEMO2 (see [`parse_control`]'s caller), so a
/// plaintext "live" share could never move and would just show a frozen position as live. It
/// renders as an ordinary location instead.
pub fn start_for(encryption: &str, content: &Element, body: &str, sent_at: i64) -> Option<LiveStart> {
    if encryption != "omemo2" {
        return None;
    }
    parse_start(content, body, sent_at)
}

/// An update or stop in `content`, if it is one.
pub fn parse_control(content: &Element) -> Option<LiveControl> {
    if let Some(el) = content.get_child("live-location-update", NS_LIVE_LOCATION) {
        let session_id = session_id(el)?;
        let lat: f64 = el.attr("lat")?.trim().parse().ok()?;
        let lon: f64 = el.attr("lon")?.trim().parse().ok()?;
        if !(lat.is_finite() && lon.is_finite() && (-90.0..=90.0).contains(&lat) && (-180.0..=180.0).contains(&lon)) {
            return None;
        }
        return Some(LiveControl::Update { session_id, lat, lon });
    }
    let el = content.get_child("live-location-stop", NS_LIVE_LOCATION)?;
    Some(LiveControl::Stop { session_id: session_id(el)? })
}

/// Whether `content` is a live-location control message at all (valid or not): such a message
/// is never shown as a bubble.
pub fn is_control(content: &Element) -> bool {
    content.get_child("live-location-update", NS_LIVE_LOCATION).is_some()
        || content.get_child("live-location-stop", NS_LIVE_LOCATION).is_some()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn el(xml: &str) -> Element {
        xml.parse().unwrap()
    }

    const T0: i64 = 1_763_769_600; // 2025-11-22T00:00:00Z

    #[test]
    fn a_location_message_can_start_a_share() {
        let content = el("<content xmlns='urn:xmpp:sce:1'><body xmlns='jabber:client'>geo:1,2</body>\
            <live-location xmlns='urn:xmpp:live-location:0' id='a1-B_2' expires='2025-11-22T01:00:00Z'/></content>");
        assert_eq!(
            parse_start(&content, "geo:1,2", T0),
            Some(LiveStart { session_id: "a1-B_2".into(), expires: T0 + 3600 })
        );
        // not a location body: no share
        assert_eq!(parse_start(&content, "hello", T0), None);
    }

    #[test]
    fn only_an_omemo2_message_starts_a_share() {
        let content = el("<content xmlns='jabber:client'><body>geo:1,2</body>\
            <live-location xmlns='urn:xmpp:live-location:0' id='s' expires='2025-11-22T01:00:00Z'/></content>");
        assert!(start_for("omemo2", &content, "geo:1,2", T0).is_some());
        for plain in ["none", "omemo", ""] {
            assert_eq!(start_for(plain, &content, "geo:1,2", T0), None, "{plain}");
        }
    }

    #[test]
    fn a_share_lasts_at_most_a_day() {
        let content = el("<m xmlns='jabber:client'>\
            <live-location xmlns='urn:xmpp:live-location:0' id='s' expires='2030-01-01T00:00:00Z'/></m>");
        assert_eq!(parse_start(&content, "geo:1,2", T0).unwrap().expires, T0 + MAX_DURATION_SECS);
    }

    #[test]
    fn bad_starts_are_ignored() {
        for xml in [
            "<live-location xmlns='urn:xmpp:live-location:0' expires='2025-11-22T01:00:00Z'/>",
            "<live-location xmlns='urn:xmpp:live-location:0' id='s' />",
            "<live-location xmlns='urn:xmpp:live-location:0' id='s' expires='tomorrow'/>",
            "<live-location xmlns='urn:xmpp:live-location:0' id='a/b' expires='2025-11-22T01:00:00Z'/>",
            "<live-location xmlns='urn:other' id='s' expires='2025-11-22T01:00:00Z'/>",
        ] {
            let content = el(&format!("<m xmlns='jabber:client'>{xml}</m>"));
            assert_eq!(parse_start(&content, "geo:1,2", T0), None, "{xml}");
        }
        let long = "x".repeat(65);
        let content = el(&format!(
            "<m xmlns='jabber:client'><live-location xmlns='urn:xmpp:live-location:0' id='{long}' expires='2025-11-22T01:00:00Z'/></m>"
        ));
        assert_eq!(parse_start(&content, "geo:1,2", T0), None);
    }

    #[test]
    fn updates_and_stops() {
        let update = el("<m xmlns='jabber:client'><live-location-update xmlns='urn:xmpp:live-location:0' id='s' lat='52.5' lon='-13.4'/></m>");
        assert!(is_control(&update));
        assert_eq!(parse_control(&update), Some(LiveControl::Update { session_id: "s".into(), lat: 52.5, lon: -13.4 }));
        let stop = el("<m xmlns='jabber:client'><live-location-stop xmlns='urn:xmpp:live-location:0' id='s'/></m>");
        assert_eq!(parse_control(&stop), Some(LiveControl::Stop { session_id: "s".into() }));
        for bad in [
            "<live-location-update xmlns='urn:xmpp:live-location:0' id='s' lat='91' lon='0'/>",
            "<live-location-update xmlns='urn:xmpp:live-location:0' id='s' lat='NaN' lon='0'/>",
            "<live-location-update xmlns='urn:xmpp:live-location:0' id='s' lat='1'/>",
            "<live-location-update xmlns='urn:xmpp:live-location:0' lat='1' lon='2'/>",
            "<live-location-stop xmlns='urn:xmpp:live-location:0' id=''/>",
        ] {
            let content = el(&format!("<m xmlns='jabber:client'>{bad}</m>"));
            assert!(is_control(&content), "still never a bubble: {bad}");
            assert_eq!(parse_control(&content), None, "{bad}");
        }
        assert!(!is_control(&el("<m xmlns='jabber:client'><body>hi</body></m>")));
    }
}
